# Generate lower bounds C * 2**e <= 10**k < (C + 1) * 2**e,
# where C has exactly 192 bits. Use integers throughout.
powers = (-289..373).map do |exponent|
  numerator, denominator = exponent >= 0 ? [10**exponent, 1] : [1, 10**-exponent]
  binary = numerator.bit_length - denominator.bit_length
  below = binary >= 0 ? numerator < denominator << binary : numerator << -binary < denominator
  binary -= 1 if below
  shift = binary - 191
  coefficient = shift >= 0 ? numerator / (denominator << shift) : (numerator << -shift) / denominator
  raise "invalid coefficient" unless coefficient.bit_length == 192
  [coefficient, shift]
end

def limbs(value)
  3.times.map {|index| 'UINT64_C(0x%016x)' % ((value >> (64 * index)) & (2**64 - 1))}.join(', ')
end

puts '/* Generated by tool/mk_zmij_precision.rb; do not edit. */'
puts 'static const uint64_t ruby_zmij_pow10_192[][3] = {'
powers.each_with_index do |(coefficient, _), index|
  puts "    {#{limbs(coefficient)}}, /* 10**#{index - 289} */"
end
puts '};'
puts 'static const int16_t ruby_zmij_pow10_192_exp[] = {'
powers.each_slice(12) {|slice| puts '    ' + slice.map(&:last).join(', ') + ','}
puts '};'
puts 'static const uint64_t ruby_zmij_precision_limits[][3] = {'
(19..50).each {|precision| puts "    {#{limbs(10**precision)}}, /* 10**#{precision} */"}
puts '};'
